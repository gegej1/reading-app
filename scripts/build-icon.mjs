// Builds the app icon: an abstract cinnabar seal (朱印) pressed onto rice
// paper, drawn from simple shapes only (rounded rectangles, no text and no
// font glyphs), then renders the icon set with `pnpm tauri icon`.
//
//   pnpm icon
//
// Writes src-tauri/icons/app-icon.svg (the source) and replaces the files
// listed in tauri.conf.json > bundle.icon plus icon.png. The other platforms'
// icons that `tauri icon` also renders are discarded.

import { spawnSync } from "node:child_process";
import { copyFileSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const iconsDir = join(root, "src-tauri", "icons");
const svgPath = join(iconsDir, "app-icon.svg");
const KEEP = ["32x32.png", "128x128.png", "128x128@2x.png", "icon.icns", "icon.ico", "icon.png"];

// Colours from src/styles/tokens.css.
const PAPER_LIGHT = "#F8F3E9";
const PAPER = "#EFE6D4";
const SEAL = "#B13A27";
const SEAL_DEEP = "#8C2B1B";
const SEAL_INK = "#FBF3E6";

// macOS icon grid: a 824 × 824 rounded square inside the 1024 canvas.
const tile = { x: 100, y: 100, size: 824, radius: 185 };
// The seal: a square turned slightly, as if stamped by hand.
const seal = { size: 520, radius: 30, angle: -7, frameInset: 26, frameWidth: 13 };
const c = 512;
const s0 = c - seal.size / 2;

/** A rounded rectangle. */
const rect = (x, y, w, h, r, fill) =>
  `<rect x="${x.toFixed(1)}" y="${y.toFixed(1)}" width="${w.toFixed(1)}" height="${h.toFixed(1)}" rx="${r}" fill="${fill}"/>`;

// The carving: four abstract marks in a 2 × 2 grid, like the four characters
// of a seal impression (白文), each built from a few bars. They are shapes,
// not glyphs. The last one widens towards its base: the "底" of 底色.
const MARKS = [
  // top left
  [[0, 0, 1, 0.17], [0, 0, 0.17, 1], [0.36, 0.41, 0.64, 0.16], [0.36, 0.83, 0.64, 0.17]],
  // top right
  [[0.42, 0, 0.16, 1], [0, 0.22, 1, 0.16], [0.1, 0.62, 0.8, 0.16]],
  // bottom left
  [[0, 0, 1, 0.16], [0, 0.84, 1, 0.16], [0, 0, 0.16, 1], [0.84, 0, 0.16, 1], [0.35, 0.35, 0.3, 0.3]],
  // bottom right
  [[0.22, 0, 0.56, 0.15], [0.08, 0.4, 0.84, 0.16], [0, 0.79, 1, 0.21]],
];
const margin = seal.frameInset + seal.frameWidth + 30;
const gutter = 40;
const cell = (seal.size - 2 * margin - gutter) / 2;
const carving = MARKS.flatMap((bars, index) => {
  const cx = s0 + margin + (index % 2) * (cell + gutter);
  const cy = s0 + margin + Math.floor(index / 2) * (cell + gutter);
  return bars.map(([x, y, w, h]) => rect(cx + x * cell, cy + y * cell, w * cell, h * cell, 5, SEAL_INK));
}).join("\n      ");

// Two worn gaps in the frame, where the stamp did not take.
const f0 = s0 + seal.frameInset - seal.frameWidth / 2 - 1;
const fw = seal.frameWidth + 2;
const wear = [
  rect(s0 + seal.size * 0.68, f0, seal.size * 0.07, fw, 0, "url(#seal)"),
  rect(f0, s0 + seal.size * 0.58, fw, seal.size * 0.05, 0, "url(#seal)"),
].join("\n    ");

const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
  <!-- 底色 app icon: an abstract cinnabar seal on rice paper, simple shapes only. -->
  <!-- Generated by scripts/build-icon.mjs; edit the script, then run: pnpm icon -->
  <defs>
    <linearGradient id="paper" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="${PAPER_LIGHT}"/>
      <stop offset="1" stop-color="${PAPER}"/>
    </linearGradient>
    <linearGradient id="seal" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="${SEAL}"/>
      <stop offset="1" stop-color="${SEAL_DEEP}"/>
    </linearGradient>
    <filter id="lift" x="-10%" y="-10%" width="120%" height="125%">
      <feDropShadow dx="0" dy="12" stdDeviation="16" flood-color="#2A2521" flood-opacity="0.28"/>
    </filter>
  </defs>
  <g filter="url(#lift)">
    ${rect(tile.x, tile.y, tile.size, tile.size, tile.radius, "url(#paper)")}
  </g>
  <g transform="rotate(${seal.angle} ${c} ${c})">
    ${rect(s0, s0, seal.size, seal.size, seal.radius, "url(#seal)")}
    <rect x="${s0 + seal.frameInset}" y="${s0 + seal.frameInset}" width="${seal.size - 2 * seal.frameInset}"
      height="${seal.size - 2 * seal.frameInset}" rx="${seal.radius - 12}" fill="none" stroke="${SEAL_INK}"
      stroke-width="${seal.frameWidth}"/>
    ${wear}
    <g>
      ${carving}
    </g>
  </g>
</svg>
`;

writeFileSync(svgPath, svg);
console.log(`wrote ${svgPath}`);

const out = mkdtempSync(join(tmpdir(), "dise-icons-"));
try {
  const result = spawnSync("pnpm", ["tauri", "icon", svgPath, "--output", out], {
    cwd: root,
    stdio: "inherit",
  });
  if (result.status !== 0) {
    console.error("pnpm tauri icon failed");
    process.exit(result.status ?? 1);
  }
  for (const name of KEEP) copyFileSync(join(out, name), join(iconsDir, name));
  console.log(`updated ${KEEP.join(", ")} in src-tauri/icons/`);
} finally {
  rmSync(out, { recursive: true, force: true });
}
